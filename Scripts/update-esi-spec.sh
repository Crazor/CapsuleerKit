#!/usr/bin/env bash
# Fetches an ESI OpenAPI snapshot and regenerates ESIKit's endpoint layer (DESIGN.md §5.1).
#
# Usage: Scripts/update-esi-spec.sh <compatibility-date> [--set-date] [--offline]
#
#   1. Downloads https://esi.evetech.net/meta/openapi.json?compatibility_date=<date>
#      to Spec/esi-openapi-<date>.json (--offline: use the file already there).
#   2. Runs swift-openapi-generator (from the nested Tools/ package) with
#      Spec/openapi-generator-config.yaml into Sources/ESIKit/Generated/.
#   3. Writes Sources/ESIKit/Generated/OperationMetadata.swift: per filtered operation the method,
#      path template, required scopes (`security`), `x-rate-limit` group and bucket, and
#      `x-client-cache-ttl`, which the generator drops.
#   4. With --set-date: updates `ESI.compatibilityDate` in Sources/ESIKit/ESI.swift. Changing the
#      date is a deliberate change: read /meta/changelog, fix the mappings, run the tests.
#
# Requires bash 3.2+, curl, python3 and a Swift 6 toolchain. Swift needs to run outside any
# outer sandbox (SwiftPM sandboxes itself).

set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
root="$(cd "$script_dir/.." && pwd)"
user_agent="CapsuleerKit-dev (+https://github.com/Crazor/CapsuleerKit)"

usage() { sed -n '2,17p' "$0" | sed 's/^# \{0,1\}//'; }

date=""
set_date=0
offline=0
while [ $# -gt 0 ]; do
  case "$1" in
    --set-date) set_date=1; shift ;;
    --offline) offline=1; shift ;;
    -h|--help) usage; exit 0 ;;
    -*) echo "Unknown option: $1" >&2; usage >&2; exit 2 ;;
    *) [ -z "$date" ] || { echo "Only one date allowed" >&2; exit 2; }; date="$1"; shift ;;
  esac
done
if ! printf '%s' "$date" | grep -Eq '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'; then
  echo "Expected a compatibility date (YYYY-MM-DD)" >&2; usage >&2; exit 2
fi

spec="$root/Spec/esi-openapi-$date.json"
config="$root/Spec/openapi-generator-config.yaml"
out="$root/Sources/ESIKit/Generated"
work="$(mktemp -d "${TMPDIR:-/tmp}/update-esi-spec.XXXXXX")"
trap 'rm -rf "$work"' EXIT

# 1. Snapshot
if [ "$offline" -eq 0 ]; then
  echo "Downloading ESI spec for $date" >&2
  curl -fsS --retry 2 -A "$user_agent" -o "$work/spec.json" \
    "https://esi.evetech.net/meta/openapi.json?compatibility_date=$date"
  python3 -I -c 'import json, sys; json.load(open(sys.argv[1]))' "$work/spec.json"
  if [ -f "$spec" ] && cmp -s "$work/spec.json" "$spec"; then
    echo "Spec/esi-openapi-$date.json is unchanged" >&2
  else
    [ -f "$spec" ] && echo "warning: Spec/esi-openapi-$date.json changed upstream; review the diff" >&2
    cp "$work/spec.json" "$spec"
  fi
elif [ ! -f "$spec" ]; then
  echo "--offline: $spec does not exist" >&2; exit 1
fi

# 2. Generator (the file comment names the snapshot)
sed "s/<date>/$date/g" "$config" > "$work/openapi-generator-config.yaml"
mkdir -p "$work/gen"
swift run --package-path "$root/Tools" --scratch-path "$root/Tools/.build" \
  swift-openapi-generator generate \
  --config "$work/openapi-generator-config.yaml" \
  --output-directory "$work/gen" \
  "$spec" >&2

# 3. OperationMetadata.swift
python3 -I - "$spec" "$config" "$date" > "$work/gen/OperationMetadata.swift" <<'PY'
import json, re, sys

spec_path, config_path, date = sys.argv[1:4]
spec = json.load(open(spec_path))

# The operation filter from the generator config (a plain YAML list under filter.operations).
wanted, in_ops = [], False
for line in open(config_path):
    if re.match(r'^\s*operations:\s*$', line):
        in_ops = True
        continue
    if in_ops:
        m = re.match(r'^\s*-\s*([A-Za-z0-9_]+)\s*$', line)
        if m:
            wanted.append(m.group(1))
        elif line.strip() and not line.strip().startswith('#'):
            in_ops = False

ops = {}
for path, item in spec["paths"].items():
    for method, op in item.items():
        if isinstance(op, dict) and op.get("operationId") in wanted:
            ops[op["operationId"]] = (method.upper(), path, op)
missing = [o for o in wanted if o not in ops]
if missing:
    sys.exit("operations not in spec: " + ", ".join(missing))

def swift_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

def lower_first(s):
    return s[:1].lower() + s[1:]

methods = {"GET": ".get", "POST": ".post", "HEAD": ".head"}
lines = [
    "// Generated by Scripts/update-esi-spec.sh from Spec/esi-openapi-%s.json. Do not edit by hand." % date,
    "// Spec extensions that swift-openapi-generator drops, per operation (DESIGN.md §5.1).",
    "import CapsuleerCore",
    "",
    "/// What the spec says about one operation beyond what the generated client encodes.",
    "struct OperationMetadata: Sendable, Hashable {",
    "    /// `x-rate-limit`: the bucket the operation draws from.",
    "    struct RateLimit: Sendable, Hashable {",
    "        var group: String",
    "        var maxTokens: Int",
    "        /// Window as written in the spec, e.g. \"15m\".",
    "        var windowSize: String",
    "        /// \"<max-tokens>/<window>\", the `ESIRequestHints.rateLimitWindow` value.",
    "        var window: String { \"\\(maxTokens)/\\(windowSize)\" }",
    "    }",
    "",
    "    var operationID: String",
    "    var method: HTTPMethod",
    "    /// Path with `{name}` placeholders, e.g. `/characters/{character_id}`.",
    "    var pathTemplate: String",
    "    /// OAuth scopes from `security`; empty for public operations.",
    "    var requiredScopes: Set<ESIScope>",
    "    var rateLimit: RateLimit?",
    "    /// `x-client-cache-ttl` in seconds.",
    "    var clientCacheTTL: Int?",
    "",
    "    static subscript(operationID: String) -> OperationMetadata? { all[operationID] }",
    "}",
    "",
    "extension OperationMetadata {",
    "    /// The compatibility date of the snapshot this table was generated from.",
    "    static let specCompatibilityDate = %s" % swift_string(date),
    "",
]
for op_id in sorted(ops):
    method, path, op = ops[op_id]
    if method not in methods:
        sys.exit("unsupported method %s for %s" % (method, op_id))
    scopes = sorted({s for req in op.get("security", []) for v in req.values() for s in v})
    rl = op.get("x-rate-limit")
    rate = "nil"
    if rl:
        rate = ".init(group: %s, maxTokens: %d, windowSize: %s)" % (
            swift_string(rl["group"]), int(rl["max-tokens"]), swift_string(rl["window-size"]))
    ttl = op.get("x-client-cache-ttl")
    ttl_s = "nil" if ttl is None else str(int(ttl))
    scopes_s = "[" + ", ".join(swift_string(s) for s in scopes) + "]"
    lines += [
        "    /// `%s %s`" % (method, path),
        "    static let %s = OperationMetadata(" % lower_first(op_id),
        "        operationID: %s, method: %s, pathTemplate: %s," % (swift_string(op_id), methods[method], swift_string(path)),
        "        requiredScopes: %s, rateLimit: %s, clientCacheTTL: %s)" % (scopes_s, rate, ttl_s),
        "",
    ]
lines += [
    "    /// All operations in the generator filter, by operationId.",
    "    static let all: [String: OperationMetadata] = [",
] + ["        %s: .%s," % (swift_string(o), lower_first(o)) for o in sorted(ops)] + [
    "    ]",
    "}",
]
print("\n".join(lines))
PY

# Replace the generated files, keeping the hand-written README.
find "$out" -maxdepth 1 -name '*.swift' -delete
cp "$work/gen/"*.swift "$out/"
echo "Generated $(ls "$work/gen" | wc -l | tr -d ' ') files into Sources/ESIKit/Generated" >&2

# 4. Compatibility date
if [ "$set_date" -eq 1 ]; then
  esi_swift="$root/Sources/ESIKit/ESI.swift"
  sed -i.bak -E "s/(public static let compatibilityDate = \")[0-9-]+(\")/\1$date\2/" "$esi_swift"
  rm -f "$esi_swift.bak"
  grep -q "compatibilityDate = \"$date\"" "$esi_swift" || { echo "Could not update ESI.compatibilityDate" >&2; exit 1; }
  echo "ESI.compatibilityDate = $date" >&2
else
  current="$(sed -nE 's/.*public static let compatibilityDate = "([0-9-]+)".*/\1/p' "$root/Sources/ESIKit/ESI.swift")"
  if [ "$current" != "$date" ]; then
    echo "note: ESI.compatibilityDate is still $current (pass --set-date to change it)" >&2
  fi
fi
